def run_analysis(file_path):
    start_time = time.time()

    print("\n" + "=" * 80)
    print("PURE PYTHON DESCRIPTIVE STATISTICS")
    print("No Pandas, No NumPy, No Third-Party Libraries")
    print("=" * 80)
    print(f"Input file: {file_path}")

    rows, column_names, columns_data = read_csv_dataset(file_path)

    column_types = {}

    for col in column_names:
        column_types[col] = infer_column_type(
            columns_data[col],
            threshold=NUMERIC_THRESHOLD
        )

    print_dataset_summary(rows, column_names, columns_data, column_types)

    print_column_statistics(column_names, columns_data, column_types)

    # Required grouped analysis 1: page_id
    if "page_id" in column_names:
        print_grouped_analysis(
            rows=rows,
            column_names=column_names,
            group_columns=["page_id"],
            max_groups=MAX_GROUPS_TO_DISPLAY
        )
    else:
        print("\npage_id column not found. Skipping page_id grouped analysis.")

    # Required grouped analysis 2: page_id + ad_id
    if "page_id" in column_names and "ad_id" in column_names:
        print_grouped_analysis(
            rows=rows,
            column_names=column_names,
            group_columns=["page_id", "ad_id"],
            max_groups=MAX_GROUPS_TO_DISPLAY
        )
    else:
        print("\npage_id/ad_id columns not found. Skipping combined grouped analysis.")

    end_time = time.time()

    print("\n" + "=" * 80)
    print("ANALYSIS COMPLETE")
    print(f"Runtime: {end_time - start_time:.2f} seconds")
    print("=" * 80)

run_analysis(INPUT_FILE)