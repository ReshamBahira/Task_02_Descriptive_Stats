def is_missing(value):
    if value is None:
        return True
    text = str(value).strip()
    return text in ("", "nan", "NaN", "None", "N/A", "NA", "null", "NULL")


def clean_number_text(value):
    return (
        str(value)
        .strip()
        .replace(",", "")
        .replace("$", "")
        .replace("%", "")
    )


def to_float_safe(value):
    if is_missing(value):
        return None, False

    text = clean_number_text(value)

    try:
        return float(text), True
    except ValueError:
        return None, False


def try_parse_range(value):
    """
    Handles values like:
    {'lower_bound': '100', 'upper_bound': '199'}

    Returns midpoint if parseable.
    Otherwise returns None.
    """
    if is_missing(value):
        return None

    text = str(value).strip()

    if not (text.startswith("{") and text.endswith("}")):
        return None

    try:
        parsed = ast.literal_eval(text)
        if not isinstance(parsed, dict):
            return None

        lower, lower_ok = to_float_safe(parsed.get("lower_bound"))
        upper, upper_ok = to_float_safe(parsed.get("upper_bound"))

        if lower_ok and upper_ok:
            return (lower + upper) / 2
        elif lower_ok:
            return lower
        else:
            return None

    except Exception:
        return None


def value_to_numeric(value):
    """
    Converts simple numeric values and dict-range values to numeric.
    """
    num, ok = to_float_safe(value)
    if ok:
        return num, True

    range_num = try_parse_range(value)
    if range_num is not None:
        return range_num, True

    return None, False


