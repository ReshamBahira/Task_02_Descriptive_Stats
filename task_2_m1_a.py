def mean(numbers):
    return sum(numbers) / len(numbers) if numbers else None


def std_dev(numbers):
    """
    Population standard deviation.
    """
    if len(numbers) < 2:
        return None

    avg = mean(numbers)
    variance = sum((x - avg) ** 2 for x in numbers) / len(numbers)
    return math.sqrt(variance)


def median(numbers):
    if not numbers:
        return None

    sorted_nums = sorted(numbers)
    n = len(sorted_nums)
    mid = n // 2

    if n % 2 == 1:
        return sorted_nums[mid]
    else:
        return (sorted_nums[mid - 1] + sorted_nums[mid]) / 2


def summarize_numeric(values):
    nums = []
    missing = 0

    for value in values:
        num, ok = value_to_numeric(value)
        if ok:
            nums.append(num)
        else:
            missing += 1

    if not nums:
        return {
            "type": "numeric",
            "count": 0,
            "missing": missing,
            "mean": None,
            "min": None,
            "max": None,
            "std_dev": None,
            "median": None
        }

    return {
        "type": "numeric",
        "count": len(nums),
        "missing": missing,
        "mean": mean(nums),
        "min": min(nums),
        "max": max(nums),
        "std_dev": std_dev(nums),
        "median": median(nums)
    }


def summarize_categorical(values, top_n=5):
    cleaned = []
    missing = 0

    for value in values:
        if is_missing(value):
            missing += 1
        else:
            cleaned.append(str(value).strip())

    counter = collections.Counter(cleaned)
    top_values = counter.most_common(top_n)

    if top_values:
        mode_value, mode_freq = top_values[0]
    else:
        mode_value, mode_freq = None, 0

    return {
        "type": "categorical",
        "count": len(cleaned),
        "missing": missing,
        "unique_count": len(counter),
        "mode": mode_value,
        "mode_frequency": mode_freq,
        "top_5_values": top_values
    }


def infer_column_type(values, sample_size=1000, threshold=0.80):
    checked = 0
    numeric_count = 0

    for value in values:
        if is_missing(value):
            continue

        checked += 1
        _, ok = value_to_numeric(value)

        if ok:
            numeric_count += 1

        if checked >= sample_size:
            break

    if checked == 0:
        return "unknown"

    numeric_ratio = numeric_count / checked

    if numeric_ratio >= threshold:
        return "numeric"
    else:
        return "categorical"


