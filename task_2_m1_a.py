def group_rows(rows, group_columns):
    """
    Creates dictionary:
    {
        group_key: [row1, row2, row3]
    }
    """
    groups = collections.defaultdict(list)

    for row in rows:
        key_parts = []

        for col in group_columns:
            key_parts.append(row.get(col, ""))

        if len(key_parts) == 1:
            group_key = key_parts[0]
        else:
            group_key = tuple(key_parts)

        groups[group_key].append(row)

    return groups


def rows_to_columns(group_rows_list, column_names):
    group_columns_data = collections.OrderedDict()

    for col in column_names:
        group_columns_data[col] = []

    for row in group_rows_list:
        for col in column_names:
            group_columns_data[col].append(row.get(col, ""))

    return group_columns_data


def summarize_group(group_rows_list, column_names):
    group_columns_data = rows_to_columns(group_rows_list, column_names)

    group_column_types = {}
    group_summary = {}

    for col in column_names:
        col_type = infer_column_type(group_columns_data[col])
        group_column_types[col] = col_type

        if col_type == "numeric":
            group_summary[col] = summarize_numeric(group_columns_data[col])
        else:
            group_summary[col] = summarize_categorical(group_columns_data[col], TOP_N_VALUES)

    return group_summary, group_column_types


def print_grouped_analysis(rows, column_names, group_columns, max_groups=5):
    print("\n" + DIVIDER)
    print(f"GROUPED ANALYSIS BY: {', '.join(group_columns)}")
    print(DIVIDER)

    missing_group_cols = [col for col in group_columns if col not in column_names]

    if missing_group_cols:
        print(f"Cannot group because these columns are missing: {missing_group_cols}")
        return

    groups = group_rows(rows, group_columns)

    print(f"Total groups found: {len(groups):,}")

    group_sizes = []
    for key, group in groups.items():
        group_sizes.append((key, len(group)))

    group_sizes = sorted(group_sizes, key=lambda x: x[1], reverse=True)

    print("\nTop groups by row count:")
    for key, size in group_sizes[:10]:
        print(f"  {key}: {size:,} rows")

    print(f"\nShowing detailed statistics for top {max_groups} groups only.")

    for group_key, group_size in group_sizes[:max_groups]:
        group_data = groups[group_key]

        print("\n" + "=" * 70)
        print(f"GROUP: {group_key}")
        print(f"ROWS : {group_size:,}")
        print("=" * 70)

        group_summary, _ = summarize_group(group_data, column_names)

        for col in column_names:
            print("\n" + "-" * 50)

            stats = group_summary[col]

            if stats["type"] == "numeric":
                print_numeric_stats(col, stats, indent="  ")
            else:
                print_categorical_stats(col, stats, indent="  ")


