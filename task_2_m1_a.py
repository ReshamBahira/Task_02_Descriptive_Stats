def format_number(value, decimals=2):
    if value is None:
        return "N/A"
    if isinstance(value, float):
        return f"{value:,.{decimals}f}"
    return str(value)


def print_dataset_summary(rows, column_names, columns_data, column_types):
    print("\n" + DIVIDER)
    print("DATASET OVERALL SUMMARY")
    print(DIVIDER)

    print(f"Row count    : {len(rows):,}")
    print(f"Column count : {len(column_names):,}")

    print("\nMissing values per column:")
    for col in column_names:
        missing = sum(1 for value in columns_data[col] if is_missing(value))
        pct = (missing / len(rows) * 100) if rows else 0
        print(f"  {col:<40} {missing:>8,}  ({pct:5.1f}%)")

    print("\nInferred data types:")
    for col in column_names:
        print(f"  {col:<40} {column_types[col]}")


def print_numeric_stats(col, stats, indent=""):
    print(f"{indent}{col} [numeric]")
    print(f"{indent}  count   : {stats['count']:,}")
    print(f"{indent}  missing : {stats['missing']:,}")
    print(f"{indent}  mean    : {format_number(stats['mean'])}")
    print(f"{indent}  min     : {format_number(stats['min'])}")
    print(f"{indent}  max     : {format_number(stats['max'])}")
    print(f"{indent}  std dev : {format_number(stats['std_dev'])}")
    print(f"{indent}  median  : {format_number(stats['median'])}")


def print_categorical_stats(col, stats, indent=""):
    print(f"{indent}{col} [categorical]")
    print(f"{indent}  count          : {stats['count']:,}")
    print(f"{indent}  missing        : {stats['missing']:,}")
    print(f"{indent}  unique values  : {stats['unique_count']:,}")
    print(f"{indent}  mode           : {stats['mode']}")
    print(f"{indent}  mode frequency : {stats['mode_frequency']:,}")
    print(f"{indent}  top 5 values   :")

    for value, freq in stats["top_5_values"]:
        short_value = str(value)
        if len(short_value) > 60:
            short_value = short_value[:57] + "..."
        print(f"{indent}    {short_value:<60} {freq:,}")


def print_column_statistics(column_names, columns_data, column_types):
    print("\n" + DIVIDER)
    print("COLUMN-LEVEL STATISTICS")
    print(DIVIDER)

    for col in column_names:
        print("\n" + "-" * 60)

        if column_types[col] == "numeric":
            stats = summarize_numeric(columns_data[col])
            print_numeric_stats(col, stats)
        else:
            stats = summarize_categorical(columns_data[col], TOP_N_VALUES)
            print_categorical_stats(col, stats)


