# =========================

def print_numeric_stats(df, col, indent=""):
    numeric_series = convert_column_to_numeric(df, col).drop_nulls()

    print(f"\n{indent}{col} [numeric]")

    if numeric_series.len() == 0:
        print(f"{indent}  No valid numeric values.")
        return

    missing = df.height - numeric_series.len()

    print(f"{indent}  count   : {numeric_series.len():,}")
    print(f"{indent}  missing : {missing:,}")
    print(f"{indent}  mean    : {numeric_series.mean():,.2f}")
    print(f"{indent}  min     : {numeric_series.min():,.2f}")
    print(f"{indent}  max     : {numeric_series.max():,.2f}")
    print(f"{indent}  std dev : {numeric_series.std(ddof=0):,.2f}")
    print(f"{indent}  median  : {numeric_series.median():,.2f}")


def print_categorical_stats(df, col, indent=""):
    values = df[col].to_list()
    clean_values = [str(v).strip() for v in values if not is_missing_value(v)]

    print(f"\n{indent}{col} [categorical]")
    print(f"{indent}  count          : {len(clean_values):,}")
    print(f"{indent}  missing        : {df.height - len(clean_values):,}")
    print(f"{indent}  unique values  : {len(set(clean_values)):,}")

    if len(clean_values) == 0:
        print(f"{indent}  mode           : N/A")
        print(f"{indent}  mode frequency : 0")
        return

    value_counts = (
        pl.DataFrame({col: clean_values})
        .group_by(col)
        .len()
        .sort("len", descending=True)
    )

    mode_value = value_counts[col][0]
    mode_frequency = value_counts["len"][0]

    print(f"{indent}  mode           : {mode_value}")
    print(f"{indent}  mode frequency : {mode_frequency:,}")
    print(f"{indent}  top 5 values   :")

    top_values = value_counts.head(TOP_N_VALUES)

    for row in top_values.iter_rows(named=True):
        value = str(row[col])
        count = row["len"]

        if len(value) > 65:
            value = value[:62] + "..."

        print(f"{indent}    {value:<65} {count:,}")


def print_column_statistics(df, column_types):
    print("\n" + DIVIDER)
    print("COLUMN-LEVEL STATISTICS")
    print(DIVIDER)

    for col in df.columns:
        if column_types[col] == "numeric":
            print_numeric_stats(df, col)
        else:
            print_categorical_stats(df, col)


# =========================
# POLARS DESCRIBE
# =========================

def print_polars_describe(df, column_types):
    print("\n" + DIVIDER)
    print("POLARS DESCRIBE OUTPUT")
    print(DIVIDER)

    numeric_columns = []

    for col in df.columns:
        if column_types[col] == "numeric":
            numeric_columns.append(convert_column_to_numeric(df, col))

    if numeric_columns:
        numeric_df = pl.DataFrame(numeric_columns)
        print("\nNumeric describe:")
        print(numeric_df.describe())
    else:
        print("\nNo numeric columns found.")

    categorical_cols = [col for col in df.columns if column_types[col] != "numeric"]

    if categorical_cols:
        print("\nCategorical describe:")
        print(df.select(categorical_cols).describe())
    else:
        print("\nNo categorical columns found.")


# =========================
# GROUPED ANALYSIS
# =========================

def print_grouped_analysis(df, group_cols, column_types):
    print("\n" + DIVIDER)
    print(f"GROUPED ANALYSIS BY: {', '.join(group_cols)}")
    print(DIVIDER)

    for col in group_cols:
        if col not in df.columns:
            print(f"Skipping group because missing column: {col}")
            return

    group_sizes = (
        df.group_by(group_cols)
        .len()
        .sort("len", descending=True)
    )

    print(f"Total groups found: {group_sizes.height:,}")

    print("\nTop groups by row count:")
    print(group_sizes.head(10))

    print(f"\nShowing detailed statistics for top {MAX_GROUPS_TO_DISPLAY} groups only.")

    top_groups = group_sizes.head(MAX_GROUPS_TO_DISPLAY)

    for row in top_groups.iter_rows(named=True):
        group_filter = None

        for col in group_cols:
            condition = pl.col(col) == row[col]
            group_filter = condition if group_filter is None else group_filter & condition

        group_df = df.filter(group_filter)

        if len(group_cols) == 1:
            group_name = row[group_cols[0]]
        else:
            group_name = tuple(row[col] for col in group_cols)

        print("\n" + "=" * 70)
        print(f"GROUP: {group_name}")
        print(f"ROWS : {group_df.height:,}")
        print("=" * 70)

        for col in df.columns:
            if column_types[col] == "numeric":
                print_numeric_stats(group_df, col, indent="  ")
            else:
                print_categorical_stats(group_df, col, indent="  ")


