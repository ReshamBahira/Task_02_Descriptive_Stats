def run_polars_analysis(file_path):
    start_time = time.time()

    print("\n" + "=" * 80)
    print("POLARS DESCRIPTIVE STATISTICS + GROUPED ANALYSIS")
    print("=" * 80)
    print(f"Input file: {file_path}")

    df = read_csv_with_python_then_polars(file_path)

    print(f"Loaded rows   : {df.height:,}")
    print(f"Loaded columns: {df.width:,}")

    column_types = infer_column_types(df)

    print_dataset_summary(df, column_types)
    print_column_statistics(df, column_types)
    print_polars_describe(df, column_types)

    groupings = choose_grouping_columns(df)

    if groupings:
        for group_cols in groupings:
            print_grouped_analysis(df, group_cols, column_types)
    else:
        print("\nNo sensible grouping columns found for this dataset.")

    end_time = time.time()

    print("\n" + "=" * 80)
    print("POLARS ANALYSIS COMPLETE")
    print(f"Runtime: {end_time - start_time:.2f} seconds")
    print("=" * 80)


# =========================
# RUN
# =========================

run_polars_analysis(INPUT_FILE)