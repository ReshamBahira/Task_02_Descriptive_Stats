def read_csv_with_python_then_polars(file_path):
    """
    Reads the CSV using Python's csv module first.
    Every value is forced to string before creating a Polars DataFrame.
    This avoids Polars schema inference errors from mixed-type columns.
    """
    if not os.path.exists(file_path):
        raise FileNotFoundError(f"File not found: {file_path}")

    rows = []
    skipped_rows = 0

    with open(file_path, "r", encoding="utf-8-sig", newline="") as file:
        reader = csv.DictReader(file)
        fieldnames = reader.fieldnames

        if fieldnames is None:
            raise ValueError("CSV file has no header row.")

        for row in reader:
            try:
                clean_row = {}

                for col in fieldnames:
                    value = row.get(col, "")
                    clean_row[col] = "" if value is None else str(value)

                rows.append(clean_row)

            except:
                skipped_rows += 1

    print("CSV loaded using Python csv module, then converted to Polars.")
    print(f"Rows skipped during safe loading: {skipped_rows:,}")

    columns_dict = {}

    for col in fieldnames:
        columns_dict[col] = [row.get(col, "") for row in rows]

    df = pl.DataFrame(columns_dict, schema={col: pl.String for col in fieldnames})

    return df


