def print_dataset_summary(df, column_types):
    print("\n" + DIVIDER)
    print("DATASET OVERALL SUMMARY")
    print(DIVIDER)

    print(f"Row count    : {df.height:,}")
    print(f"Column count : {df.width:,}")

    print("\nMissing values per column:")
    for col in df.columns:
        values = df[col].to_list()
        missing = sum(is_missing_value(v) for v in values)
        pct = missing / df.height * 100 if df.height else 0
        print(f"  {col:<45} {missing:>8,} ({pct:5.1f}%)")

    print("\nInferred data types:")
    for col in df.columns:
        print(f"  {col:<45} {column_types[col]}")


