def is_missing_value(value):
    if value is None:
        return True
    text = str(value).strip()
    return text in ["", "nan", "NaN", "None", "N/A", "NA", "null", "NULL"]


def parse_range_value(value):
    if is_missing_value(value):
        return None

    text = str(value).strip()

    try:
        return float(
            text.replace(",", "")
                .replace("$", "")
                .replace("%", "")
        )
    except:
        pass

    if not (text.startswith("{") and text.endswith("}")):
        return None

    try:
        parsed = ast.literal_eval(text)

        if not isinstance(parsed, dict):
            return None

        lower = parsed.get("lower_bound")
        upper = parsed.get("upper_bound")

        lower = float(str(lower).replace(",", "")) if lower not in [None, ""] else None
        upper = float(str(upper).replace(",", "")) if upper not in [None, ""] else None

        if lower is not None and upper is not None:
            return (lower + upper) / 2
        elif lower is not None:
            return lower
        else:
            return None

    except:
        return None


def convert_column_to_numeric(df, col):
    values = df[col].to_list()
    numeric_values = [parse_range_value(v) for v in values]
    return pl.Series(col, numeric_values, dtype=pl.Float64)


def infer_column_types(df):
    column_types = {}

    for col in df.columns:
        values = df[col].to_list()
        non_missing = [v for v in values if not is_missing_value(v)]

        if len(non_missing) == 0:
            column_types[col] = "unknown"
            continue

        numeric_values = [parse_range_value(v) for v in non_missing]
        numeric_count = sum(v is not None for v in numeric_values)
        numeric_ratio = numeric_count / len(non_missing)

        if numeric_ratio >= 0.80:
            column_types[col] = "numeric"
        else:
            column_types[col] = "categorical"

    return column_types


def choose_grouping_columns(df):
    cols = set(df.columns)
    groupings = []

    if "page_id" in cols:
        groupings.append(["page_id"])

    if "page_id" in cols and "ad_id" in cols:
        groupings.append(["page_id", "ad_id"])

    if "page_id" in cols and "post_id" in cols:
        groupings.append(["page_id", "post_id"])

    if "account_id" in cols:
        groupings.append(["account_id"])
    elif "author_id" in cols:
        groupings.append(["author_id"])
    elif "username" in cols:
        groupings.append(["username"])
    elif "handle" in cols:
        groupings.append(["handle"])

    unique_groupings = []
    for grouping in groupings:
        if grouping not in unique_groupings:
            unique_groupings.append(grouping)

    return unique_groupings


