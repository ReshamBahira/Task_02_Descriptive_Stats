# =========================

def is_missing_series(series):
    return series.isna() | series.astype(str).str.strip().isin(
        ["", "nan", "NaN", "None", "N/A", "NA", "null", "NULL"]
    )


def parse_range_value(value):
    if pd.isna(value):
        return None

    text = str(value).strip()

    # Try normal numeric first
    try:
        return float(
            text.replace(",", "")
                .replace("$", "")
                .replace("%", "")
        )
    except:
        pass

    # Try dictionary-like range values
    if not (text.startswith("{") and text.endswith("}")):
        return None

    try:
        parsed = ast.literal_eval(text)

        if not isinstance(parsed, dict):
            return None

        lower = parsed.get("lower_bound")
        upper = parsed.get("upper_bound")

        lower = float(str(lower).replace(",", "")) if lower not in [None, ""] else None
        upper = float(str(upper).replace(",", "")) if upper not in [None, ""] else None

        if lower is not None and upper is not None:
            return (lower + upper) / 2
        elif lower is not None:
            return lower
        else:
            return None

    except:
        return None


def convert_possible_numeric(series):
    numeric = pd.to_numeric(
        series.astype(str)
        .str.replace(",", "", regex=False)
        .str.replace("$", "", regex=False)
        .str.replace("%", "", regex=False),
        errors="coerce"
    )

    # If many values failed, try parsing dict/range strings
    if numeric.notna().mean() < 0.50:
        numeric = series.apply(parse_range_value)

    return pd.to_numeric(numeric, errors="coerce")


def infer_column_types(df):
    column_types = {}

    for col in df.columns:
        original_non_missing = ~is_missing_series(df[col])
        non_missing_count = original_non_missing.sum()

        if non_missing_count == 0:
            column_types[col] = "unknown"
            continue

        numeric_version = convert_possible_numeric(df[col])
        numeric_ratio = numeric_version.notna().sum() / non_missing_count

        if numeric_ratio >= 0.80:
            column_types[col] = "numeric"
        else:
            column_types[col] = "categorical"

    return column_types


def choose_grouping_columns(df):
    cols = set(df.columns)
    groupings = []

    # Facebook Ads
    if "page_id" in cols:
        groupings.append(["page_id"])

    if "page_id" in cols and "ad_id" in cols:
        groupings.append(["page_id", "ad_id"])

    # Facebook Posts
    if "page_id" in cols and "post_id" in cols:
        groupings.append(["page_id", "post_id"])

    # Twitter/X datasets
    if "account_id" in cols:
        groupings.append(["account_id"])
    elif "author_id" in cols:
        groupings.append(["author_id"])
    elif "username" in cols:
        groupings.append(["username"])
    elif "handle" in cols:
        groupings.append(["handle"])

    # Remove duplicate groupings
    unique_groupings = []
    for g in groupings:
        if g not in unique_groupings:
            unique_groupings.append(g)

    return unique_groupings


