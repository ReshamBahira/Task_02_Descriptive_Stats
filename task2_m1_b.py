def read_csv_safely(file_path):
    if not os.path.exists(file_path):
        raise FileNotFoundError(f"File not found: {file_path}")

    try:
        df = pd.read_csv(
            file_path,
            encoding="utf-8-sig",
            low_memory=False
        )
        print("CSV loaded using default Pandas C engine.")

    except pd.errors.ParserError:
        print("ParserError found. Retrying with Python engine and skipping malformed rows.")

        df = pd.read_csv(
            file_path,
            encoding="utf-8-sig",
            engine="python",
            on_bad_lines="skip"
        )

        print("CSV loaded using Python engine.")
        print("Malformed rows were skipped.")

    return df


