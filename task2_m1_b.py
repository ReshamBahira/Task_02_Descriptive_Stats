# PANDAS DESCRIBE
# =========================

def print_pandas_describe(df, column_types):
    print("\n" + DIVIDER)
    print("PANDAS DESCRIBE OUTPUT")
    print(DIVIDER)

    numeric_df = pd.DataFrame()

    for col in df.columns:
        if column_types[col] == "numeric":
            numeric_df[col] = convert_possible_numeric(df[col])

    print("\nNumeric describe:")
    if not numeric_df.empty:
        print(numeric_df.describe())
    else:
        print("No numeric columns found.")

    categorical_cols = [col for col in df.columns if column_types[col] != "numeric"]

    print("\nCategorical describe:")
    if categorical_cols:
        print(df[categorical_cols].astype(str).describe())
    else:
        print("No categorical columns found.")


# =========================
# GROUPED ANALYSIS
# =========================

def print_grouped_analysis(df, group_cols, column_types):
    print("\n" + DIVIDER)
    print(f"GROUPED ANALYSIS BY: {', '.join(group_cols)}")
    print(DIVIDER)

    for col in group_cols:
        if col not in df.columns:
            print(f"Skipping group because column missing: {col}")
            return

    grouped = df.groupby(group_cols, dropna=False)
    group_sizes = grouped.size().sort_values(ascending=False)

    print(f"Total groups found: {len(group_sizes):,}")

    print("\nTop groups by row count:")
    print(group_sizes.head(10))

    print(f"\nShowing detailed statistics for top {MAX_GROUPS_TO_DISPLAY} groups only.")

    top_group_keys = group_sizes.head(MAX_GROUPS_TO_DISPLAY).index

    for key in top_group_keys:
        if len(group_cols) == 1:
            group_df = df[df[group_cols[0]] == key]
        else:
            key_tuple = key if isinstance(key, tuple) else (key,)
            mask = pd.Series(True, index=df.index)

            for col, value in zip(group_cols, key_tuple):
                mask &= df[col] == value

            group_df = df[mask]

        print("\n" + "=" * 70)
        print(f"GROUP: {key}")
        print(f"ROWS : {len(group_df):,}")
        print("=" * 70)

        for col in df.columns:
            if column_types[col] == "numeric":
                print_numeric_stats(group_df, col, indent="  ")
            else:
                print_categorical_stats(group_df, col, indent="  ")


# =========================
# MAIN
# =========================

def run_pandas_analysis(file_path):
    start_time = time.time()

    print("\n" + "=" * 80)
    print("PANDAS DESCRIPTIVE STATISTICS + GROUPED ANALYSIS")
    print("=" * 80)
    print(f"Input file: {file_path}")

    df = read_csv_safely(file_path)

    print(f"Loaded rows   : {len(df):,}")
    print(f"Loaded columns: {len(df.columns):,}")

    column_types = infer_column_types(df)

    print_dataset_summary(df, column_types)
    print_column_statistics(df, column_types)
    print_pandas_describe(df, column_types)

    groupings = choose_grouping_columns(df)

    if groupings:
        for group_cols in groupings:
            print_grouped_analysis(df, group_cols, column_types)
    else:
        print("\nNo sensible grouping columns found for this dataset.")

    end_time = time.time()

    print("\n" + "=" * 80)
    print("PANDAS ANALYSIS COMPLETE")
    print(f"Runtime: {end_time - start_time:.2f} seconds")
    print("=" * 80)


# =========================
# RUN
# =========================

run_pandas_analysis(INPUT_FILE)