def print_dataset_summary(df, column_types):
    print("\n" + DIVIDER)
    print("DATASET OVERALL SUMMARY")
    print(DIVIDER)

    print(f"Row count    : {len(df):,}")
    print(f"Column count : {len(df.columns):,}")

    print("\nMissing values per column:")
    for col in df.columns:
        missing = is_missing_series(df[col]).sum()
        pct = missing / len(df) * 100 if len(df) else 0
        print(f"  {col:<45} {missing:>8,} ({pct:5.1f}%)")

    print("\nInferred data types:")
    for col in df.columns:
        print(f"  {col:<45} {column_types[col]}")


def print_numeric_stats(df, col, indent=""):
    numeric = convert_possible_numeric(df[col]).dropna()
    missing = len(df) - len(numeric)

    print(f"\n{indent}{col} [numeric]")

    if numeric.empty:
        print(f"{indent}  No valid numeric values.")
        return

    print(f"{indent}  count   : {numeric.count():,}")
    print(f"{indent}  missing : {missing:,}")
    print(f"{indent}  mean    : {numeric.mean():,.2f}")
    print(f"{indent}  min     : {numeric.min():,.2f}")
    print(f"{indent}  max     : {numeric.max():,.2f}")
    print(f"{indent}  std dev : {numeric.std(ddof=0):,.2f}")
    print(f"{indent}  median  : {numeric.median():,.2f}")


def print_categorical_stats(df, col, indent=""):
    series = df[col]
    non_missing = series[~is_missing_series(series)].astype(str).str.strip()
    missing = len(df) - len(non_missing)

    print(f"\n{indent}{col} [categorical]")
    print(f"{indent}  count          : {len(non_missing):,}")
    print(f"{indent}  missing        : {missing:,}")
    print(f"{indent}  unique values  : {non_missing.nunique():,}")

    if len(non_missing) == 0:
        print(f"{indent}  mode           : N/A")
        print(f"{indent}  mode frequency : 0")
        return

    value_counts = non_missing.value_counts()

    print(f"{indent}  mode           : {value_counts.index[0]}")
    print(f"{indent}  mode frequency : {value_counts.iloc[0]:,}")
    print(f"{indent}  top 5 values   :")

    for value, count in value_counts.head(TOP_N_VALUES).items():
        value = str(value)
        if len(value) > 65:
            value = value[:62] + "..."
        print(f"{indent}    {value:<65} {count:,}")


def print_column_statistics(df, column_types):
    print("\n" + DIVIDER)
    print("COLUMN-LEVEL STATISTICS")
    print(DIVIDER)

    for col in df.columns:
        if column_types[col] == "numeric":
            print_numeric_stats(df, col)
        else:
            print_categorical_stats(df, col)


